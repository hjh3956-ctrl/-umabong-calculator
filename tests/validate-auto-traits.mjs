import assert from 'node:assert/strict';
import {canAutoAcceptTrait,normalizeTraitReview,requireTraitReviews,traitReviewMarkup} from '../dist/trait-review.mjs';
import {parseFieldText} from '../dist/photo-parser.mjs';
import {photoApplication} from '../dist/photo-recognizer.mjs';
const exact=parseFieldText('체력조절',6);
assert.equal(exact.quality,'exact');
assert.equal(canAutoAcceptTrait(exact),true);
for(const trait of [null,{value:null,quality:'exact'},{value:'UNKNOWN',quality:'exact'},{...exact,quality:'review'},{...exact,quality:'missing'}])assert.equal(canAutoAcceptTrait(trait),false);
const record={lane:4,name:'test',fields:Array.from({length:6},()=>({value:3})),trait:exact,traitConfirmed:canAutoAcceptTrait(exact),traitAutomatic:true};
const applied=photoApplication([record])[0];
const review=normalizeTraitReview({lane:applied.lane,raw:applied.traitRaw,confirmed:applied.traitConfirmed,automatic:applied.traitAutomatic});
assert.doesNotThrow(()=>requireTraitReviews([review]));
const markup=traitReviewMarkup(review);
assert.ok(markup.includes('성향 자동 입력 완료'));
assert.ok(!markup.includes('성향 확인 필요'));
assert.ok(markup.includes('checked'));
assert.ok(markup.includes('<details>'));
assert.ok(!markup.includes('사진과 성향 값이 일치합니다'));
const pending=normalizeTraitReview({...review,confirmed:false});
assert.equal(pending.automatic,false);
assert.throws(()=>requireTraitReviews([pending]),/4번/);
assert.ok(traitReviewMarkup(pending).includes('성향 확인 필요'));
const manual=normalizeTraitReview({...review,automatic:false});
assert.ok(traitReviewMarkup(manual).includes('성향 입력 완료'));
console.log('Exact traits auto-apply; uncertain, conflicting, missing and deselected traits require review; manual edits remain accepted.');
